"""Report export (Markdown, PDF). Generated content and human-authored content are always visibly separate: nothing a human
types can appear as a finding, and every export carries the generation provenance and the content hash."""
from __future__ import annotations

import io
import re
from xml.sax.saxutils import escape

from agent_engine.reporting.render import render_markdown

STATUS_LABEL = {"pending": "pending - no human has reviewed this report", "approved": "approved by a human reviewer",
                "changes_requested": "a human reviewer requested changes"}


def display_title(content: dict, editable: dict) -> str:
    return editable.get("title") or f"Research report: {content['question'][:100]}"


def slug(title: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", title).strip("-").lower()[:60] or "report"


def _quote(text: str) -> str:
    return "\n".join("> " + line if line.strip() else ">" for line in text.splitlines()) or ">"


def _evidence_items(content: dict) -> list[dict]:
    return [f for fs in content["findings"].values() for f in fs]


def provenance_lines(meta: dict, content: dict, editable: dict) -> list[str]:
    return [f"Generated by RESEARCHOS from run `{meta['run_id']}` on {meta['generated_at']}; content hash `{meta['content_sha256']}`; "
            f"report version {meta['version']} ({meta['edits']} human edit(s)).",
            "The generated analysis is deterministic and extractive; the human sections below it are authored by people and are "
            "not verified by the system."]


def to_markdown(content: dict, editable: dict, meta: dict) -> str:
    review = editable.get("review") or {"status": "pending"}
    out = [f"# {display_title(content, editable)}", "", *[f"_{line}_" for line in provenance_lines(meta, content, editable)], "",
           f"**Human review:** {STATUS_LABEL.get(review['status'], review['status'])}"
           + (f" ({review.get('reviewer')}: {review.get('comment')})" if review.get("reviewer") else ""), "",
           render_markdown(content).replace("# Research report", "## Generated analysis", 1).rstrip(), ""]
    items = _evidence_items(content)
    if items:
        out += ["## Evidence passages (source text)", ""]
        for f in items:
            c = f["citation"]
            out += [f"- **{f['claim_id']}** `{c['document_id']}` p.{c['page_number']} `{c['passage_id']}`",
                    _quote(c.get("source_text") or "(source text unavailable)"), ""]
    out += ["## Human notes (not generated, not verified)", ""]
    if not editable.get("sections") and not editable.get("annotations"):
        out += ["_No human notes._", ""]
    for s in editable.get("sections", []):
        out += [f"**{s['heading'].replace(chr(10), ' ')}**", "", _quote(s["body"]), ""]  # quoted: it can never pose as a section
    if editable.get("annotations"):
        out += ["### Annotations on claims", ""]
        for cid, text in sorted(editable["annotations"].items()):
            out += [f"- **{cid}**: {text.replace(chr(10), ' ')}"]
        out.append("")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ PDF
def _pdf_text(text: str, counter: list[int]) -> str:
    safe = text.encode("cp1252", "replace").decode("cp1252")  # the built-in PDF fonts cover Western European text only
    counter[0] += sum(1 for a, b in zip(text, safe) if a != b) + abs(len(text) - len(safe))
    return escape(safe)


def to_pdf(content: dict, editable: dict, meta: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    base = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=base["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("s", parent=body, fontSize=8, leading=10.5, textColor=colors.HexColor("#444444"))
    quote = ParagraphStyle("q", parent=body, leftIndent=10, textColor=colors.HexColor("#222244"), fontName="Helvetica-Oblique")
    h1, h2, h3 = base["Title"], base["Heading2"], base["Heading3"]
    replaced = [0]
    flow: list = []

    def p(text, style=body):
        flow.append(Paragraph(_pdf_text(text, replaced), style))

    def bullet(text, style=body):
        flow.append(Paragraph("&bull; " + _pdf_text(text, replaced), style))

    review = editable.get("review") or {"status": "pending"}
    p(display_title(content, editable), h1)
    for line in provenance_lines(meta, content, editable):
        p(line, small)
    p(f"Human review: {STATUS_LABEL.get(review['status'], review['status'])}", body)
    p(content["novelty_statement"], quote)
    p("Question: " + content["question"], body)
    p(f"Status: {content['status']}", body)

    s = content["scope"]
    p("Scope of the search", h2)
    if s.get("corpus"):
        bullet(f"Indexed corpus: {s['corpus']['documents']} documents, {s['corpus']['passages']} passages")
    bullet("Search terms: " + (", ".join(s["terms"]) or "n/a"))
    bullet(f"Accepted evidence: {s['accepted_passages']} passage(s) from {s['accepted_documents']} document(s)")
    if s.get("uncovered_terms"):
        bullet("Question terms with no accepted evidence: " + ", ".join(s["uncovered_terms"]))
    bullet("Not searched: " + s["unsearched"])

    p("Closest documents", h2)
    for d in content["closest_documents"] or []:
        bullet(f"{d['title']} ({d.get('year') or 'year unknown'}; DOI {d.get('doi') or 'n/a'}; licence {d.get('license') or 'n/a'})")
    if not content["closest_documents"]:
        p("None: no accepted documents.", small)

    p("Verified findings (quoted from the documents)", h2)
    any_f = False
    for kind, label in (("method", "Methods"), ("result", "Results"), ("limitation", "Stated limitations")):
        items = content["findings"][kind]
        if items:
            any_f = True
            p(label, h3)
            for f in items:
                c = f["citation"]
                bullet(f"{f['claim_id']}: \"{f['text']}\"")
                p(f"{c['document_id']}, p.{c['page_number']}, passage {c['passage_id']}", small)
    if not any_f:
        p("No claim passed verification.", small)

    if content["needs_review"]:
        p("Needs human review", h2)
        for n in content["needs_review"]:
            bullet(f"{n['claim_id']}: \"{n['text']}\" - {'; '.join(n['reasons'])}")
    p("Unsupported claims", h2)
    for u in content["unsupported_claims"]:
        bullet(f"{u['claim_id']}: \"{u['text']}\" - {'; '.join(u['reasons'])}")
    if not content["unsupported_claims"]:
        p("None.", small)

    p("Candidate gaps (not findings)", h2)
    for g in content["candidate_gaps"]:
        bullet(f"{g['id']} ({g['kind']}): {g['statement']}")
    if not content["candidate_gaps"]:
        p("None identified.", small)
    p("Hypotheses (untested proposals, not findings)", h2)
    for h in content["hypotheses"]:
        p(f"{h['id']} [{h['status']}] {h['statement']}", body)
        bullet("Assumptions: " + " ".join(h["assumptions"]), small)
        bullet("Falsification criteria: " + h["falsification_criteria"], small)
    if not content["hypotheses"]:
        p("None drafted.", small)

    p("Uncertainty", h2)
    for u in content["uncertainties"]:
        bullet(u)
    p("Limitations", h2)
    for u in content["limitations"]:
        bullet(u)

    items = _evidence_items(content)
    if items:
        p("Evidence passages (source text)", h2)
        for f in items:
            c = f["citation"]
            p(f"{f['claim_id']} - {c['document_id']} p.{c['page_number']} passage {c['passage_id']}", small)
            p(c.get("source_text") or "(source text unavailable)", quote)

    p("Human notes (not generated, not verified)", h2)
    for sec in editable.get("sections", []):
        p(sec["heading"], h3)
        p(sec["body"], quote)
    for cid, text in sorted((editable.get("annotations") or {}).items()):
        bullet(f"{cid}: {text}")
    if not editable.get("sections") and not editable.get("annotations"):
        p("No human notes.", small)
    if replaced[0]:
        flow.insert(5, Paragraph(_pdf_text(f"Note: {replaced[0]} character(s) outside Western European text were replaced with '?' "
                                           "in this PDF; the Markdown and JSON exports keep the original text.", [0]), small))

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                      title=display_title(content, editable)[:120], author="RESEARCHOS").build(flow)
    return buf.getvalue()
