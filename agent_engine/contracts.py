"""Typed contracts shared by every agent, tool and the scheduler (pydantic v2, extra fields forbidden)."""
from __future__ import annotations

from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class RunStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    PAUSED = "paused"  # user pause, or quiesced while waiting for human approval
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"
    STOPPED_LIMIT = "stopped_limit"


class TaskStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    SUCCEEDED = "succeeded"
    FAILED = "failed"
    AWAITING_APPROVAL = "awaiting_approval"
    REJECTED = "rejected"
    SKIPPED = "skipped"
    CANCELLED = "cancelled"


TERMINAL_RUN = {RunStatus.COMPLETED, RunStatus.FAILED, RunStatus.CANCELLED, RunStatus.STOPPED_LIMIT}
TERMINAL_TASK = {TaskStatus.SUCCEEDED, TaskStatus.FAILED, TaskStatus.REJECTED, TaskStatus.SKIPPED, TaskStatus.CANCELLED}
# A dependency in one of these states means the dependent task can never run.
DEAD_TASK = {TaskStatus.FAILED, TaskStatus.REJECTED, TaskStatus.SKIPPED, TaskStatus.CANCELLED}


class EvidenceReference(_Strict):
    document_id: str = Field(min_length=1)
    page_number: int | None = Field(default=None, ge=1)
    passage_id: str | None = None


class ProposedTask(_Strict):
    """A follow-up task an agent asks the scheduler to create. Subject to policy and run limits."""

    key: str = Field(min_length=1, max_length=64)  # local name so proposals can depend on each other
    agent_type: str = Field(min_length=1)
    title: str = Field(max_length=200)
    input: dict[str, Any] = Field(default_factory=dict)
    depends_on: list[str] = Field(default_factory=list)  # sibling proposal keys or existing task ids
    followup: bool = False  # True = another refinement round (counts against max_iterations)


class ModelNote(_Strict):
    """Free text from the local language model. Always untrusted; never evidence."""

    text: str
    tokens_used: int = Field(ge=0)
    model: str = "researchos-experimental-small"
    trusted: Literal[False] = False
    disclaimer: str = "Generated by an experimental small language model. Untrusted draft - not evidence."


class AgentOutput(_Strict):
    task_id: str
    agent_type: str
    status: Literal["ok", "partial", "insufficient_evidence"]
    summary: str = Field(max_length=2000)
    findings: list[str] = Field(default_factory=list)
    evidence: list[EvidenceReference] = Field(default_factory=list)
    uncertainties: list[str] = Field(default_factory=list)
    proposed_tasks: list[ProposedTask] = Field(default_factory=list)
    model_notes: list[ModelNote] = Field(default_factory=list)
    # Structured payload for downstream agents. Convention: data["assessment"] = verdict on the evidence so far.
    data: dict[str, Any] = Field(default_factory=dict)


class RunLimits(_Strict):
    """Hard stop controls so agents can never loop or spend without bound."""

    max_tasks: int = Field(default=40, gt=0)
    max_iterations: int = Field(default=2, ge=0)  # refinement rounds beyond the first plan
    max_model_tokens: int = Field(default=2000, ge=0)  # prompt + generated tokens across the whole run
    max_runtime_s: float = Field(default=300.0, gt=0)
    max_retries: int = Field(default=2, ge=0)  # per task, after the first attempt
    task_timeout_s: float = Field(default=60.0, gt=0)
    max_concurrency: int = Field(default=4, gt=0)
    retry_backoff_s: float = Field(default=0.5, ge=0)  # attempt n waits backoff * 2**(n-1)


class TaskSpec(BaseModel):
    """What an agent receives. `dependency_outputs` holds the validated outputs of finished dependencies."""

    id: str
    run_id: str
    agent_type: str
    title: str
    input: dict[str, Any] = Field(default_factory=dict)
    depends_on: list[str] = Field(default_factory=list)
    iteration: int = 0
    parent_task_id: str | None = None
    attempt: int = 1
    dependency_outputs: dict[str, AgentOutput] = Field(default_factory=dict)


class RunResult(BaseModel):
    run_id: str
    status: RunStatus
    stop_reason: str | None = None
    task_counts: dict[str, int] = Field(default_factory=dict)
    summary: dict[str, Any] = Field(default_factory=dict)
