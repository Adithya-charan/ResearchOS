"""Generate the synthetic research-style corpus and its licence manifest (all text is CC0, written by project code)."""
import argparse
from datetime import date

import _bootstrap  # noqa: F401
from model.common import repo_root, sha256_file
from model.data.manifest import DocRecord, write_manifest
from model.data.synthetic import generate_documents


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--docs", type=int, default=6000)
    ap.add_argument("--seed", type=int, default=20260101)
    ap.add_argument("--name", default="synthetic_v1")
    args = ap.parse_args()

    root = repo_root() / "datasets"
    raw_dir = root / "raw" / args.name
    raw_dir.mkdir(parents=True, exist_ok=True)
    today = date.today().isoformat()
    records = []
    for doc_id, text in generate_documents(args.docs, args.seed):
        path = raw_dir / f"{doc_id}.txt"
        path.write_text(text, encoding="utf-8", newline="\n")
        records.append(
            DocRecord(
                doc_id=doc_id,
                path=f"raw/{args.name}/{doc_id}.txt",
                sha256=sha256_file(path),
                source=f"researchos.data.synthetic seed={args.seed}",
                license="CC0-1.0 (generated by project code)",
                acquired=today,
                allowed_use=["training", "evaluation", "search"],
                bytes=path.stat().st_size,
                notes="template-generated; contains no real scientific findings",
            )
        )
    manifest = root / "manifests" / f"{args.name}.jsonl"
    write_manifest(manifest, records)
    total = sum(r.bytes for r in records)
    print(f"wrote {len(records)} documents ({total / 1e6:.1f} MB) -> {raw_dir}")
    print(f"manifest -> {manifest}")


if __name__ == "__main__":
    main()
