"""Compatibility spike for the PyMuPDF licensing decision (P10): can pdfminer.six (MIT) supply what research/corpus/extract_pdf.py needs?

It builds the repository's own fixture PDFs, extracts each with PyMuPDF (current backend) and pdfminer.six, and compares
  * page text: word-sequence similarity (difflib) per page,
  * heading signal: for every heading in the fixtures, the font size pdfminer reports for that line versus the body size.
Run:  python scripts/pdf_backend_spike.py [--site-packages DIR]   (pdfminer.six is NOT a project dependency; point DIR at a
`pip install --target DIR pdfminer.six` folder). Output: artifacts/evaluation/pdf_backend_spike.json

Limits: fixture PDFs are generated by PyMuPDF itself (simple, single-column, embedded base-14 fonts), so this says nothing about real,
multi-column, scanned or ligature-heavy papers. It is a feasibility check, not a validation of a replacement.
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import statistics
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def words(text: str) -> list[str]:
    return re.findall(r"\w+", text.lower())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--site-packages", default=None)
    ap.add_argument("--out", default=str(ROOT / "artifacts" / "evaluation" / "pdf_backend_spike.json"))
    a = ap.parse_args()
    if a.site_packages:
        sys.path.insert(0, a.site_packages)
    from pdfminer.high_level import extract_pages
    from pdfminer.layout import LTChar, LTTextContainer

    from research.corpus.extract_pdf import extract_pdf
    from tests.corpus_fixtures import PAPERS, build_library

    results, ratios, heading_checks = [], [], []
    with tempfile.TemporaryDirectory() as d:
        lib = build_library(Path(d))
        for key, path in lib.items():
            ref = extract_pdf(path)
            miner_pages = list(extract_pages(str(path)))
            for ref_page, mp in zip(ref.pages, miner_pages):
                mtext, sizes = [], []
                for el in mp:
                    if isinstance(el, LTTextContainer):
                        mtext.append(el.get_text())
                        for line in el:
                            chars = [c for c in line if isinstance(c, LTChar)]
                            if chars:
                                sizes.append((line.get_text().strip(), statistics.mean(c.size for c in chars)))
                r = difflib.SequenceMatcher(None, words(ref_page.raw_text), words(" ".join(mtext)), autojunk=False).ratio()
                ratios.append(r)
                body = statistics.median(s for _, s in sizes) if sizes else 0
                for heading, _ in PAPERS[key]["sections"]:
                    hit = next((s for t, s in sizes if t.strip().lower() == heading.strip().lower()), None)
                    if hit is not None:
                        heading_checks.append({"paper": key, "heading": heading, "heading_size": round(hit, 1), "body_median": round(body, 1),
                                               "larger_than_body": hit > body + 0.5})
            results.append({"paper": key, "pages_pymupdf": len(ref.pages), "pages_pdfminer": len(miner_pages)})
    report = {
        "papers": results,
        "page_text_similarity": {"pages": len(ratios), "mean": round(statistics.mean(ratios), 4), "min": round(min(ratios), 4)},
        "headings": {"found_by_pdfminer": len(heading_checks), "expected": sum(len(p["sections"]) for p in PAPERS.values()),
                     "distinguishable_by_font_size": sum(h["larger_than_body"] for h in heading_checks)},
        "scope": "synthetic fixture PDFs made by PyMuPDF; feasibility only, not validation on real papers",
    }
    Path(a.out).write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
